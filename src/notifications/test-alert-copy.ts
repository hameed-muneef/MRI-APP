// نص نتيجة «تجربة التنبيه»: يقول بصراحة إن كان الاختبار جرى والتنبيهات متوقفة،
// حتى لا يظن المستخدم أن التنبيهات ستصله بعد إيقافها من الإعدادات العامة.
export function testAlertMessage(mode: 'none' | 'tone' | 'file', globalEnabled: boolean): string {
  const base = mode === 'none' ? 'أُرسل التنبيه التجريبي (صامت).' : 'أُرسل التنبيه التجريبي وشُغِّل الصوت.';
  return globalEnabled ? base : `${base} تنبيهاتك متوقفة من إعدادات الهدوء والإشعارات، وهذا اختبار للصوت فقط.`;
}
